#!/usr/bin/env node
// Builds results/results.md from results/raw/*.jsonl: median, min and max per task x mode, cold and
// warm cache in separate rows. Smoke runs are listed apart and never mixed into the table.

import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { RAW_DIR, RESULTS_MD } from "../../shared/paths.js";
import { MODE_LABELS, type RunRecord } from "./record.js";

export function loadRecords(dir = RAW_DIR): RunRecord[] {
  if (!existsSync(dir)) return [];
  return readdirSync(dir)
    .filter((f) => f.endsWith(".jsonl"))
    .sort()
    .flatMap((f) =>
      readFileSync(path.join(dir, f), "utf8")
        .split("\n")
        .filter((l) => l.trim())
        .map((l) => JSON.parse(l) as RunRecord),
    );
}

export function median(xs: number[]): number {
  const s = [...xs].sort((a, b) => a - b);
  const m = Math.floor(s.length / 2);
  return s.length % 2 ? s[m]! : (s[m - 1]! + s[m]!) / 2;
}

const fmtInt = (n: number) => Math.round(n).toLocaleString("en-US");
const fmtUsd = (n: number) => `$${n.toFixed(4)}`;
const fmtS = (ms: number) => `${(ms / 1000).toFixed(1)} s`;

function cell(xs: number[], f: (n: number) => string): string {
  if (xs.length === 0) return "–";
  if (xs.length === 1) return f(xs[0]!);
  return `${f(median(xs))} (${f(Math.min(...xs))}–${f(Math.max(...xs))})`;
}

export function renderTable(records: RunRecord[]): string {
  const groups = new Map<string, RunRecord[]>();
  for (const r of records) {
    const key = [r.task, r.mode, r.cache_state, r.model].join("|");
    groups.set(key, [...(groups.get(key) ?? []), r]);
  }
  const keys = [...groups.keys()].sort();
  const rows = keys.map((k) => {
    const rs = groups.get(k)!;
    const [task, mode, cache, model] = k.split("|") as [string, RunRecord["mode"], string, string];
    const ok = rs.filter((r) => r.correct).length;
    return [
      task,
      MODE_LABELS[mode],
      model,
      cache,
      String(rs.length),
      `${ok}/${rs.length}`,
      cell(rs.map((r) => r.usage.total_input), fmtInt),
      cell(rs.map((r) => r.usage.cache_read), fmtInt),
      cell(rs.map((r) => r.usage.output), fmtInt),
      cell(rs.map((r) => r.requests), fmtInt),
      cell(rs.map((r) => r.wall_ms), fmtS),
      cell(rs.map((r) => r.cost_usd), fmtUsd) + (rs[0]!.cost_source === "claude-code-estimate" ? " *" : ""),
    ];
  });
  const header = ["Task", "Mode", "Model", "Cache", "Runs", "Correct", "Input tokens (all)", "of which cache reads", "Output tokens", "Requests", "Wall time", "Cost"];
  return [
    `| ${header.join(" | ")} |`,
    `|${header.map(() => "---").join("|")}|`,
    ...rows.map((r) => `| ${r.join(" | ")} |`),
  ].join("\n");
}

/** A mode E run without Code Mode active is a classic run in disguise: never shown as E. */
export function isInvalid(r: RunRecord): boolean {
  if (r.mode !== "E") return false;
  if (r.extra?.code_mode_active === false) return true;
  const tools = r.extra?.tools_at_init;
  return Array.isArray(tools) && !tools.includes("REPL") && r.extra?.source !== "interactive-transcript";
}

export function renderReport(records: RunRecord[], now = new Date()): string {
  const invalid = records.filter(isInvalid);
  const valid = records.filter((r) => !isInvalid(r));
  const real = valid.filter((r) => !r.smoke);
  const smoke = valid.filter((r) => r.smoke);
  const parts = [
    "# Results",
    "",
    `Generated by \`npm run report\` on ${now.toISOString().slice(0, 10)} from \`results/raw/*.jsonl\`. Do not edit by hand.`,
    "",
    "Each cell: median (min–max) over the runs in that row. Input tokens are summed over every request of a run:",
    "uncached input + cache writes + cache reads. Cold = the run's first request read nothing from the prompt cache;",
    "cold and warm runs are never mixed in one row. Cost for modes A-C comes from the price table in",
    "`bench/src/prices.ts`; `*` marks Claude Code's own client-side estimate (`total_cost_usd`), which on a",
    "subscription is not money spent.",
    "",
  ];
  parts.push(real.length ? renderTable(real) : "_No benchmark runs yet._");
  if (smoke.length) {
    parts.push("", "## Smoke runs (plumbing checks, not results)", "", renderTable(smoke));
  }
  if (invalid.length) {
    parts.push("", "## Invalid runs (left out of every table)", "");
    for (const r of invalid) {
      parts.push(`- ${r.task} mode ${r.mode} rep ${r.rep}${r.smoke ? " (smoke)" : ""}, batch \`${r.batch_id}\`: ${String(r.extra?.note ?? "Code Mode requested but not active.")}`);
    }
  }
  const failures = real.filter((r) => r.error);
  if (failures.length) {
    parts.push("", "## Runs that ended in an error", "");
    for (const r of failures) parts.push(`- ${r.task} ${r.mode} rep ${r.rep} (${r.batch_id}): ${r.error}`);
  }
  return `${parts.join("\n")}\n`;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  writeFileSync(RESULTS_MD, renderReport(loadRecords()));
  console.log(`wrote ${RESULTS_MD}`);
}
